const haikusById = new Map(haikus.map((h) => [h.id, h]));

export function getHaikusByIds(ids: number[]): Haiku[] {
  return ids
    .map((id) => haikusById.get(id))
    .filter((h): h is Haiku => h !== undefined);
}
